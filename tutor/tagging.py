def subject_of(number):
    """문항 번호(1~15)로 과목을 돌려준다."""
    return SUBJECT_BY_BLOCK[(number - 1) // 5]


def tax_of(stem, body):
    """세무회계 문항의 세목을 돌려준다. 법 이름이 질문에 있으면 그것, 아니면 낱말 점수가 가장 큰 세목."""
    for law, tax in LAW_NAMES.items():
        if law in stem:
            return tax
    scores = {tax: _score(words, stem, body) for tax, words in TAX_KEYWORDS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] > 0 else TAX_CORP  # 아무 단서가 없으면 문제 수가 가장 많은 법인세로 둔다


def _score(words, stem, body):
    """낱말이 질문 문장에 나오면 STEM_WEIGHT, 그 밖의 글에 나오면 1 로 센다."""
    return sum(STEM_WEIGHT * stem.count(w) + body.count(w) for w in words)


def unit_of(group, stem, body):
    """과목(또는 세목) group 의 단원 이름을 돌려준다. 질문 문장 → 전체 글 순서로 찾는다."""
    rules = UNIT_RULES[group]
    return _first_unit(rules, stem) or _first_unit(rules, body) or DEFAULT_UNIT


def _first_unit(rules, text):
    for unit, patterns in rules:
        if any(re.search(p, text) for p in patterns):
            return unit
    return None


def tag_question(number, question, choices, explanation):
    """(과목, 세목, 단원) 을 돌려준다. 세목은 세무회계만 값이 있고 나머지는 빈 문자열."""
    body = " ".join([question, *choices, explanation or ""])
    subject = subject_of(number)
    if subject != "세무회계":
        return subject, "", unit_of(subject, question, body)
    tax = tax_of(question, body)
    return subject, tax, unit_of(tax, question, body)
